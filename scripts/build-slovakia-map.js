// Builds public/js/slovakia-map.js (the map of the national page, slta.sk) from the boundaries of the 8 regions of Slovakia.
// Source of the boundaries: geoBoundaries (gbOpen, SVK ADM1, simplified), licence CC BY 4.0, https://www.geoboundaries.org
//   curl -L -o adm1.geojson https://github.com/wmgeolab/geoBoundaries/raw/main/releaseData/gbOpen/SVK/ADM1/geoBoundaries-SVK-ADM1_simplified.geojson
// Run: node scripts/build-slovakia-map.js <adm1.geojson>      (writes public/js/slovakia-map.js: the projected, simplified path of every region)
// The file defines window.SK_MAP = { w, h, project(lon, lat) -> [x, y], regions: [{ iso, sk, en, d, cx, cy }] }.
const fs = require('fs');
const path = require('path');

const src = process.argv[2];
if (!src) { console.error('Usage: node scripts/build-slovakia-map.js <adm1.geojson>'); process.exit(1); }
const geo = JSON.parse(fs.readFileSync(src, 'utf8'));

const NAMES = {
  'SK-BL': ['Bratislavský kraj', 'Bratislava Region'], 'SK-TA': ['Trnavský kraj', 'Trnava Region'], 'SK-TC': ['Trenčiansky kraj', 'Trenčín Region'],
  'SK-NI': ['Nitriansky kraj', 'Nitra Region'], 'SK-ZI': ['Žilinský kraj', 'Žilina Region'], 'SK-BC': ['Banskobystrický kraj', 'Banská Bystrica Region'],
  'SK-PV': ['Prešovský kraj', 'Prešov Region'], 'SK-KI': ['Košický kraj', 'Košice Region'],
};

// the frame: Slovakia plus room for the names of the neighbours
const LON0 = 16.38; const LON1 = 23.02; const LAT0 = 47.42; const LAT1 = 49.92;
const COS = Math.cos(48.7 * Math.PI / 180);
const W = 1000;
const K = W / ((LON1 - LON0) * COS);
const H = Math.round((LAT1 - LAT0) * K);
const project = (lon, lat) => [(lon - LON0) * COS * K, (LAT1 - lat) * K];

// Douglas-Peucker on the projected points
function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Array(pts.length).fill(false);
  keep[0] = true; keep[pts.length - 1] = true;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let max = 0; let idx = -1;
    const [ax, ay] = pts[a]; const [bx, by] = pts[b];
    const dx = bx - ax; const dy = by - ay; const len = Math.hypot(dx, dy) || 1;
    for (let i = a + 1; i < b; i += 1) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len;
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol && idx > 0) { keep[idx] = true; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
// a closed ring is cut at the point furthest from its start and both halves are simplified (Douglas-Peucker needs two different ends)
function simplifyRing(ring, tol) {
  const pts = ring.slice(0, ring[0][0] === ring[ring.length - 1][0] && ring[0][1] === ring[ring.length - 1][1] ? -1 : undefined);
  let far = 1; let best = 0;
  pts.forEach((p, i) => { const d = Math.hypot(p[0] - pts[0][0], p[1] - pts[0][1]); if (d > best) { best = d; far = i; } });
  const a = simplify(pts.slice(0, far + 1), tol);
  const b = simplify([...pts.slice(far), pts[0]], tol);
  return [...a, ...b.slice(1, -1)];
}
const area = (r) => { let s = 0; for (let i = 0; i < r.length; i += 1) { const [x1, y1] = r[i]; const [x2, y2] = r[(i + 1) % r.length]; s += x1 * y2 - x2 * y1; } return s / 2; };
const centroid = (r) => { let cx = 0; let cy = 0; let a = 0; for (let i = 0; i < r.length; i += 1) { const [x1, y1] = r[i]; const [x2, y2] = r[(i + 1) % r.length]; const f = x1 * y2 - x2 * y1; cx += (x1 + x2) * f; cy += (y1 + y2) * f; a += f; } a *= 3; return [cx / a, cy / a]; };

const regions = geo.features.map((f) => {
  const rings = f.geometry.type === 'Polygon' ? f.geometry.coordinates : f.geometry.coordinates.flat();
  const projected = rings.map((ring) => ring.map(([lon, lat]) => project(lon, lat)));
  const simple = projected.map((r) => simplifyRing(r, 0.45)).filter((r) => r.length >= 4 && Math.abs(area(r)) > 8);
  const biggest = simple.reduce((m, r) => (Math.abs(area(r)) > Math.abs(area(m)) ? r : m), simple[0]);
  const [cx, cy] = centroid(biggest);
  const d = simple.map((r) => `M${r.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join('L')}Z`).join('');
  const iso = f.properties.shapeISO;
  return { iso, sk: (NAMES[iso] || [f.properties.shapeName])[0], en: (NAMES[iso] || [f.properties.shapeName, f.properties.shapeName])[1], d, cx: +cx.toFixed(1), cy: +cy.toFixed(1) };
});

const out = `// Generated by scripts/build-slovakia-map.js — do not edit by hand.
// The 8 regions of Slovakia (boundaries: geoBoundaries gbOpen, CC BY 4.0, https://www.geoboundaries.org), projected to a ${W} x ${H} frame.
window.SK_MAP = {
  w: ${W}, h: ${H},
  // the projection: longitude / latitude -> x, y of the frame (the same one the paths were drawn with)
  project: function (lon, lat) { return [(lon - ${LON0}) * ${COS.toFixed(6)} * ${K.toFixed(4)}, (${LAT1} - lat) * ${K.toFixed(4)}]; },
  regions: ${JSON.stringify(regions)},
};
`;
fs.writeFileSync(path.join(__dirname, '..', 'public', 'js', 'slovakia-map.js'), out);
console.log(`ok: ${regions.length} regions, ${(out.length / 1024).toFixed(1)} kB, frame ${W} x ${H}`);
