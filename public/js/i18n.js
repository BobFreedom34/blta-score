// The texts of one part of the site (seasons, matches, communities…) are in i18n-<part>.js, which a page loads before this file only when it
// needs them; each pushes { sk, en } into window.I18N_PARTS. This file keeps the texts every page needs (nav, login, footer, the scripts of common.js).
// scripts/check-i18n-split.js checks that every page loads the parts for every key it uses.
if (typeof window !== 'undefined' && window.I18N_PARTS) {
  window.I18N_PARTS.forEach((part) => {
    Object.assign(TRANSLATIONS.sk, part.sk);
    Object.assign(TRANSLATIONS.en, part.en);
  });
}

// Looks up `key` in the current language, falling back to English, then to
// the raw key itself (so a missing translation fails loud/visible instead
// of silently rendering blank). `vars` does simple {name} interpolation.
const missingKeys = new Set();
function t(key, vars) {
  let s = (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) || TRANSLATIONS.en[key];
  if (!s) {
    // a key written like a key (page.title) that no loaded file has: a page without the i18n-<part>.js it needs; shown as the key itself, and said once on the console
    if (/^[A-Za-z][A-Za-z0-9]*(\.[A-Za-z0-9_]+)+$/.test(String(key)) && TRANSLATIONS.en[key] === undefined && !missingKeys.has(key)) {
      missingKeys.add(key);
      if (typeof console !== 'undefined') console.warn(`i18n: missing text "${key}" (is the i18n-<part>.js of its page loaded?)`);
    }
    s = key;
  }
  if (vars) {
    for (const k of Object.keys(vars)) {
      // a function, so that a $& or $' inside the value (a name written by a player) stays text
      s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), () => String(vars[k]));
    }
  }
  // {brand} and {place} stand for the brand of the city of the page and its place: "BLTA" and "v Bratislave" / "in Bratislava", or "SLTA Košice" and "v Košiciach" / "in Košice"
  // (written in Backend > Cities), so a heading written once reads right in every city
  if (s.indexOf('{brand}') !== -1 || s.indexOf('{place}') !== -1) {
    const city = typeof window !== 'undefined' && window.CITY && !window.CITY.first ? window.CITY : null;
    const place = currentLang === 'en' ? `in ${city ? city.name : 'Bratislava'}` : (city ? (city.locative || '') : 'v Bratislave');
    s = s.replace(/\{brand\}/g, city ? city.brand : 'BLTA').replace(/\{place\}/g, place).replace(/\s+([.,:;])/g, '$1').trim();
  }
  return s;
}

// A text written in both languages next to the code that shows it, for the screens whose texts a script builds (the tournament / season manage page):
// tl('Slovenský text', 'English text'). The whole page is in one language (the address, or the saved choice), so nothing is left in the other one.
function tl(sk, en) {
  return currentLang === 'en' ? en : sk;
}

// a number with its noun in the right form: Slovak 1 zápas / 2 zápasy / 5 zápasov, English 1 match / 2 matches
function nounFor(n, sk1, sk2to4, sk5, en1, en2) {
  if (currentLang === 'en') return n === 1 ? en1 : en2;
  return n === 1 ? sk1 : (n >= 2 && n <= 4 ? sk2to4 : sk5);
}

function setLang(lang) {
  currentLang = lang;
  try { localStorage.setItem(LANG_STORAGE_KEY, lang); } catch { /* ignore */ }
  // on a page with an address per language the switch goes to the same page in the other language
  const other = typeof BLTA_LOCALIZE !== 'undefined' && BLTA_LOCALIZE.switchUrl ? BLTA_LOCALIZE.switchUrl(lang) : null;
  if (other) location.href = other;
  else location.reload();
}

// Walks every element carrying a data-i18n* attribute and fills it in from
// the dictionary — covers the three shapes static markup needs: plain
// text content, a placeholder, or (for the one spot with an embedded
// <span>, the login modal's intro line) raw trusted HTML we authored
// ourselves rather than user input.
function applyStaticTranslations() {
  document.documentElement.lang = currentLang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
}

function initLangSwitcher() {
  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
    btn.addEventListener('click', () => {
      if (btn.dataset.lang !== currentLang) setLang(btn.dataset.lang);
    });
  });
}

applyStaticTranslations();
initLangSwitcher();
